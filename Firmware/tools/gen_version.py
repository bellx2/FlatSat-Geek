# PlatformIO pre-build script: writes version_gen.h with the build date/time
# and the git commit count / hash, so the LCD can show which firmware is running.
# Only files that include version.h are recompiled when it changes.
import datetime
import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

proj = env.subst("$PROJECT_DIR")  # noqa: F821


def git(*args):
    try:
        return subprocess.check_output(
            ["git", "-C", proj] + list(args), stderr=subprocess.DEVNULL, text=True
        ).strip()
    except Exception:
        return ""


count = git("rev-list", "--count", "HEAD") or "0"
short = git("rev-parse", "--short", "HEAD") or "nogit"
dirty = "+" if git("status", "--porcelain", "--untracked-files=no", "--", ".", ":(exclude)build") else ""
now = datetime.datetime.now()

text = (
    "// Generated by tools/gen_version.py - do not edit or commit.\n"
    "#define FW_BUILD_NUMBER %s\n"
    '#define FW_BUILD_HASH "%s%s"\n'
    '#define FW_BUILD_DATE "%s"\n'
) % (count, short, dirty, now.strftime("%Y-%m-%d %H:%M"))

path = os.path.join(proj, "version_gen.h")
old = None
if os.path.exists(path):
    with open(path) as f:
        old = f.read()
if old != text:
    with open(path, "w") as f:
        f.write(text)

# version.hからFW_VERSIONを読んで出力ファイル名に反映
import re

version_h = os.path.join(proj, "version.h")
fw_version = "unknown"
if os.path.exists(version_h):
    with open(version_h) as f:
        m = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', f.read())
        if m:
            fw_version = m.group(1)

env_name = env.subst("$PIOENV")  # noqa: F821
env.Replace(PROGNAME="flatsat-%s-v%s" % (env_name, fw_version))  # noqa: F821
